/// The country's English name, or null for a code that isn't in [kCountries].
String? countryName(String? code) {
  if (code == null) return null;
  final upper = code.toUpperCase();
  for (final country in kCountries) {
    if (country.code == upper) return country.name;
  }
  return null;
}

/// True for a code that is in [kCountries] (case-insensitive).
bool isKnownCountry(String? code) => countryName(code) != null;

/// The flag emoji for a two-letter code ("LK" -> 🇱🇰), built from the
/// regional-indicator letters. Empty for anything that isn't two letters.
String flagEmoji(String? code) {
  if (code == null || code.length != 2) return '';
  final upper = code.toUpperCase().codeUnits;
  if (upper.any((unit) => unit < 65 || unit > 90)) return '';
  return String.fromCharCodes(upper.map((unit) => 0x1F1E6 + (unit - 65)));
}

/// "🇱🇰 Sri Lanka" — what to show for a code.
String countryLabel(String? code) {
  final name = countryName(code);
  if (name == null) return '';
  final flag = flagEmoji(code);
  return flag.isEmpty ? name : '$flag $name';
}

